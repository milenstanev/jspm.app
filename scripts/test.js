#!/usr/bin/env node
/**
 * Smoke tests to verify the project builds and runs correctly.
 * Run with: node scripts/test.js
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const projectRoot = path.join(__dirname, '..');
let passed = 0;
let failed = 0;

function test(name, fn) {
  try {
    fn();
    console.log(`  ✓ ${name}`);
    passed++;
  } catch (err) {
    console.log(`  ✗ ${name}`);
    console.log(`    ${err.message}`);
    failed++;
  }
}

console.log('\n--- Project smoke tests ---\n');

test('users-form unit tests (schema → Bootstrap 3, not a todo list)', () => {
  execSync('node --test users-form.test.js', {
    cwd: projectRoot,
    stdio: 'pipe',
  });
});

// Test 1: config.js exists (generated by jspm)
test('config.js exists', () => {
  const configPath = path.join(projectRoot, 'config.js');
  if (!fs.existsSync(configPath)) {
    throw new Error('config.js not found. Run: node node_modules/jspm/jspm.js install -y');
  }
});

// Test 2: jspm_packages exists
test('jspm_packages directory exists', () => {
  const jspmPath = path.join(projectRoot, 'jspm_packages');
  if (!fs.existsSync(jspmPath) || !fs.statSync(jspmPath).isDirectory()) {
    throw new Error('jspm_packages not found. Run: node node_modules/jspm/jspm.js install -y');
  }
});

// Test 3: system.js exists in jspm_packages
test('SystemJS loader exists', () => {
  const systemPath = path.join(projectRoot, 'jspm_packages', 'system.js');
  if (!fs.existsSync(systemPath)) {
    throw new Error('jspm_packages/system.js not found');
  }
});

// Test 4: Source files exist
test('src/index.js exists', () => {
  const indexPath = path.join(projectRoot, 'src', 'index.js');
  if (!fs.existsSync(indexPath)) {
    throw new Error('src/index.js not found');
  }
});

// Test 5: Gulp dev build completes
test('gulp dev build completes', () => {
  execSync('npx gulp dev', {
    cwd: projectRoot,
    stdio: 'pipe'
  });
});

// Test 6: index.html contains dev mode (SystemJS.import)
test('index.html configured for dev mode', () => {
  const htmlPath = path.join(projectRoot, 'index.html');
  const content = fs.readFileSync(htmlPath, 'utf8');
  if (!content.includes('SystemJS.import') || !content.includes('src/index.js')) {
    throw new Error('index.html missing SystemJS.import for dev mode');
  }
  if (!content.includes('bootstrap.min.css') || !content.includes('src/app.css')) {
    throw new Error('index.html missing Bootstrap / app stylesheet');
  }
  if (
    content.indexOf('users-form.lib.js') < 0 ||
    content.indexOf('users-form.lib.js') > content.indexOf('users-form.js')
  ) {
    throw new Error('index.html must load users-form.lib.js before users-form.js');
  }
});

test('home is a Bootstrap 3 schema form, not a todo list', () => {
  const html = fs.readFileSync(path.join(projectRoot, 'src', 'home', 'home.html'), 'utf8');
  const component = fs.readFileSync(
    path.join(projectRoot, 'src', 'home', 'home.component.js'),
    'utf8'
  );
  if (html.includes('todo') || component.includes('todo')) {
    throw new Error('home still contains the old todo list');
  }
  ['form-group', 'form-control', 'btn btn-primary', 'jspm-user-form'].forEach((token) => {
    if (!html.includes(token)) {
      throw new Error(`home.html missing Bootstrap 3 token: ${token}`);
    }
  });
  if (!component.includes('/api/users') || component.includes('/api/user"') || component.includes("/api/user'")) {
    throw new Error('home must load schema-ui collection /api/users');
  }
  if (!component.includes("emit('userUpdated'")) {
    throw new Error('home submit must emit userUpdated on window.desktopUi');
  }
});

test('Vercel serves committed public/ and does not rebuild with jspm', () => {
  const vercel = JSON.parse(fs.readFileSync(path.join(projectRoot, 'vercel.json'), 'utf8'));
  if (vercel.installCommand != null || vercel.buildCommand != null) {
    throw new Error('vercel.json must not install or build on Vercel (jspm/GitHub rate limits)');
  }
  if (vercel.outputDirectory !== 'public') {
    throw new Error('vercel outputDirectory must be public');
  }
  const rewrite = (vercel.rewrites || [])[0] && vercel.rewrites[0].source;
  if (!rewrite || !rewrite.includes('src/') || !rewrite.includes('dist/')) {
    throw new Error('SPA rewrite must exclude dist/ and src/ so CSS and bundles are not rewritten to HTML');
  }
  const distHeader = (vercel.headers || []).find((entry) => entry.source === '/dist/(.*)');
  const cache = distHeader && distHeader.headers.find((h) => h.key === 'Cache-Control');
  if (!cache || String(cache.value).includes('immutable') || String(cache.value).includes('31536000')) {
    throw new Error('dist Cache-Control must not be immutable year-long');
  }
});

// Test 7: ESLint passes on core source files
test('ESLint passes on core source files', () => {
  execSync('npx eslint "src/index.js" "src/futureRoutes.js" "src/home/home.module.js" --max-warnings 999', {
    cwd: projectRoot,
    stdio: 'pipe'
  });
});

// Test 8: Prod build completes
test('gulp prod build completes', () => {
  execSync('npx gulp prod', {
    cwd: projectRoot,
    stdio: 'pipe',
    timeout: 60000
  });
});

// Test 9: Prod loads SystemJS, vendor/app bundles, and lazy-chunk overrides
test('index.html configured for prod after build', () => {
  const htmlPath = path.join(projectRoot, 'index.html');
  const content = fs.readFileSync(htmlPath, 'utf8');
  if (content.includes('system-csp-production.js')) {
    throw new Error('prod must use jspm_packages/system.js');
  }
  if (!content.includes('jspm_packages/system.js')) {
    throw new Error('index.html missing system.js for prod');
  }
  if (!content.includes('dist/core.bundle.js')) {
    throw new Error('index.html missing dist/core.bundle.js for prod');
  }
  if (!content.includes('dist/app.bundle.js')) {
    throw new Error('index.html missing dist/app.bundle.js for prod');
  }
  if (!content.includes('dist/prod-bundle-overrides.js')) {
    throw new Error('index.html missing dist/prod-bundle-overrides.js for prod');
  }
  const prodBlock = content.split('<!-- !dev -->')[1];
  if (!prodBlock || !prodBlock.split('<!-- /!dev -->')[0]) {
    throw new Error('index.html missing !dev block');
  }
  const prodInner = prodBlock.split('<!-- /!dev -->')[0];
  if (!prodInner.includes('<script src="config.js">')) {
    throw new Error('prod block must load config.js for SystemJS map/paths (overrides disable Babel)');
  }
  const overridesPath = path.join(projectRoot, 'dist', 'prod-bundle-overrides.js');
  const overrides = fs.readFileSync(overridesPath, 'utf8');
  if (!overrides.includes('"bundles"')) {
    throw new Error('prod-bundle-overrides.js must configure SystemJS bundles for lazy chunks');
  }
  if (!overrides.includes('dist/home.bundle.js')) {
    throw new Error('prod-bundle-overrides.js must map homeComponent to dist/home.bundle.js');
  }
  if (overrides.includes('defaultJSExtensions')) {
    throw new Error('prod overrides must not set defaultJSExtensions (breaks bundle module ids)');
  }
  const homeChunk = fs.readFileSync(
    path.join(projectRoot, 'dist', 'home.bundle.js'),
    'utf8'
  );
  if (!homeChunk.includes('jspm-user-form')) {
    throw new Error('home chunk must contain the schema form, not a todo list');
  }
});

test('prod emits lazy route chunk bundles', () => {
  ['home', 'counter', 'timer', 'notes'].forEach((name) => {
    const chunkPath = path.join(projectRoot, 'dist', `${name}.bundle.js`);
    if (!fs.existsSync(chunkPath)) {
      throw new Error(`missing dist/${name}.bundle.js after prod build`);
    }
  });
});

console.log(`\n--- Results: ${passed} passed, ${failed} failed ---\n`);

if (failed > 0) {
  process.exit(1);
}

// Restore dev mode so index.html is ready for development
execSync('node node_modules/gulp/bin/gulp.js dev', {
  cwd: projectRoot,
  stdio: 'pipe'
});
